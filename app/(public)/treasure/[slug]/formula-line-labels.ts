export function getFormulaLineLabels(slug: string, name: string, expression: string) {
  const lineCount = expression.split(/\s*;\s*|:\s{2,}|\n+/).filter(Boolean).length
  return FORMULA_LINE_LABELS[`${slug}::${name}`]
    ?? Array.from({ length: lineCount }, (_, index) => index === 0 ? name : `${name} · รูปที่ ${index + 1}`)
}
