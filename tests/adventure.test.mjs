import assert from 'node:assert/strict'
import { readFileSync, existsSync } from 'node:fs'
import { stripTypeScriptTypes } from 'node:module'
const source = readFileSync(new URL('../lib/adventure-topics.ts', import.meta.url), 'utf8')
const { ADVENTURE_TOPICS: topics, ADVENTURE_REGIONS: regions, ADVENTURE_DESTINATIONS: destinations, getTopicArtwork, MAP_LOCATIONS: locations, filterAdventureTopics, getTopicProgress, getPracticeHref, buildTopicProgress } = await import(`data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(source)).toString('base64')}`)
assert.equal(topics.length, 14)
assert.equal(new Set(topics.map(t => t.id)).size, 14)
assert.deepEqual(regions.map(r => topics.filter(t => t.grade === r.grade).length), [6,5,3])
assert.equal(locations.length, topics.length)
assert.deepEqual(destinations.flatMap(d => d.topics).sort(), topics.map(t => t.id).sort())
for (const topic of topics) assert.ok(existsSync(new URL(`../public${getTopicArtwork(topic.id)}`, import.meta.url)))
assert.ok(locations.every(([x,y]) => x >= 9 && x <= 90 && y >= 15 && y <= 92))
for (const region of regions) assert.ok(existsSync(new URL(`../public${region.image}`, import.meta.url)))
assert.equal(filterAdventureTopics('all','  MATRIX ')[0].id,'matrix')
assert.equal(filterAdventureTopics('ม.6','แคลคูลัส')[0].id,'calculus')
assert.equal(filterAdventureTopics('ม.4','calculus').length,0)
assert.equal(filterAdventureTopics('all','not-a-topic').length,0)
assert.equal(getPracticeHref('calculus',true),'/practice/calculus')
assert.equal(getPracticeHref('calculus',false),'/login?next=%2Fpractice%2Fcalculus')
assert.deepEqual(getTopicProgress({},'set'),{done:0,total:50,percent:0})
assert.deepEqual(getTopicProgress({set:{done:80,total:50}},'set'),{done:50,total:50,percent:100})
assert.deepEqual(getTopicProgress({set:{done:0,total:0}},'set'),{done:0,total:0,percent:0})
assert.deepEqual(buildTopicProgress([{topic_id:'set',question_id:'1'},{topic_id:'set',question_id:'1'},{topic_id:'set',question_id:'2'}]),{set:{done:2,total:50}})
assert.equal(buildTopicProgress(Array.from({length:60},(_,i)=>({topic_id:'set',question_id:String(i)}))).set.done,50)
const guides = readFileSync(new URL('../content/treasure-data.json',import.meta.url),'utf8')
for (const topic of topics) assert.ok(guides.includes(`${topic.id}-formula-guide`),topic.id)
console.log('14 topics, region mappings, artwork, filters, progress, guides and return paths passed')
